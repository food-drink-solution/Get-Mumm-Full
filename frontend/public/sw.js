// Kill switch: this service worker unregisters itself and all caches.
// Deployed because VITE_ENABLE_SW is disabled. Any browser that previously
// registered the old SW will receive this file and clean up automatically.

self.addEventListener("install", () => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.map((k) => caches.delete(k))))
      .then(() => self.registration.unregister())
      .then(() => self.clients.matchAll())
      .then((clients) => clients.forEach((client) => client.navigate(client.url)))
  );
});

